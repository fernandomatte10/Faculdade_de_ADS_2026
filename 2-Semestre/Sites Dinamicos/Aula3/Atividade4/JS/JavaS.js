let n = Number(prompt("Digite um numero: "));

if(n == 0) {
    alert("Numero é igual a zero\n");
    //console.log("Numero é igual a zero\n");
} else if (n > 0) {
    alert("Seu numero é positivo\n");
    //console.log("Seu numero é positivo\n");
} else {
    alert("Seu numero é negativo\n");
    //console.log("Seu numero é negativo\n");
}